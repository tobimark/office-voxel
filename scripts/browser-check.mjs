import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

const output = fileURLToPath(new URL('../.artifacts/', import.meta.url));
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--enable-webgl', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (['error', 'warning'].includes(message.type())) errors.push(message.text()); });
const url = process.env.DEMO_URL || 'http://127.0.0.1:5196/';
try {
  await page.goto(url);
  await page.waitForFunction(() => window.PixOfficeVoxel);
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${output}/office-desktop.png`, fullPage: true });
  await page.getByRole('button', { name: '人物特写', exact: true }).click();
  await page.getByRole('button', { name: '挥手招呼', exact: false }).click();
  await page.waitForTimeout(1600);
  await page.screenshot({ path: `${output}/character-wave.png` });
  assert.equal(await page.evaluate(() => window.PixOfficeVoxel.getState().actors[0].action), 'wave');
  await page.getByRole('button', { name: '惊讶', exact: false }).click();
  assert.equal(await page.evaluate(() => window.PixOfficeVoxel.getState().actors[0].expression), 'surprise');
  await page.locator('#flexibility').fill('0');
  assert.equal(await page.evaluate(() => window.PixOfficeVoxel.getState().flexibility), 0);
  await page.locator('#flexibility').fill('85');
  await page.getByRole('button', { name: '坐下工作', exact: false }).click();
  await page.waitForFunction(() => window.PixOfficeVoxel.getState().actors[0].action === 'work', null, { timeout: 15000 });
  await page.getByRole('button', { name: '人物特写', exact: true }).click();
  await page.waitForTimeout(1600);
  await page.screenshot({ path: `${output}/character-work.png` });
  await page.getByRole('button', { name: '散步走走', exact: false }).click();
  const start = await page.evaluate(() => window.PixOfficeVoxel.getState().actors[0].position);
  await page.waitForTimeout(1500);
  const moved = await page.evaluate(() => window.PixOfficeVoxel.getState().actors[0].position);
  assert.ok(Math.hypot(start.x - moved.x, start.z - moved.z) > .2);
  await page.getByRole('button', { name: '暂停动画', exact: true }).click();
  const stopped = await page.evaluate(() => window.PixOfficeVoxel.getState().actors[0].position);
  await page.waitForTimeout(400);
  assert.deepEqual(await page.evaluate(() => window.PixOfficeVoxel.getState().actors[0].position), stopped);
  await page.getByRole('button', { name: '阿森', exact: false }).click();
  assert.equal(await page.evaluate(() => window.PixOfficeVoxel.getState().selected), 1);
  await page.getByRole('button', { name: '调节', exact: true }).click();
  await page.locator('#lighting').selectOption('night');
  assert.equal(await page.evaluate(() => window.PixOfficeVoxel.getState().lighting), 'night');
  await page.locator('#pixelated').check();
  await page.locator('#pixelated').uncheck();
  await page.locator('#lighting').selectOption('day');
  await page.getByRole('button', { name: '关闭调节', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '全景', exact: true }).click();
  await page.waitForTimeout(1500);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: `${output}/office-mobile.png`, fullPage: true });
  await page.setViewportSize({ width: 1024, height: 768 });
  await page.waitForTimeout(500);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: `${output}/office-tablet.png`, fullPage: true });
  await page.goto(`${url}embed.html`);
  await page.getByRole('button', { name: '让小麦打个招呼' }).click();
  const embedded = page.frames().find(frame => frame.url().includes('embed=1'));
  assert.ok(embedded);
  await embedded.waitForFunction(() => window.PixOfficeVoxel.getState().actors[0].action === 'wave');
  await page.getByRole('button', { name: '看看人物表情' }).click();
  await embedded.waitForFunction(() => window.PixOfficeVoxel.getState().camera === 'person');
  assert.equal(await embedded.evaluate(() => window.PixOfficeVoxel.getState().actors[0].expression), 'surprise');
  await page.waitForTimeout(1500);
  await page.screenshot({ path: `${output}/office-embed.png`, fullPage: true });
  await page.goto(`${url}?embed=1`);
  await page.waitForFunction(() => window.PixOfficeVoxel);
  assert.equal(await page.locator('.inspector').isVisible(), false);
  assert.equal(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight), true);
  const reduced = await browser.newPage({ reducedMotion: 'reduce' });
  await reduced.goto(url); await reduced.waitForFunction(() => window.PixOfficeVoxel);
  assert.equal(await reduced.evaluate(() => window.PixOfficeVoxel.getState().paused), true);
  await reduced.close();
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'passed', checks: ['WebGL render', 'wave', 'expression', 'flexibility', 'work arrival', 'walking', 'pause', 'selection', 'lighting', 'pixel mode', 'mobile/tablet overflow', 'iframe command bridge', 'embed', 'reduced motion', 'console clean'], state: await page.evaluate(() => window.PixOfficeVoxel.getState()), output }, null, 2));
} finally { await browser.close(); }
